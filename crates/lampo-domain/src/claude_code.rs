//! The Claude Code integration, as pure data: the files of Lampo's local plugin (marketplace,
//! manifest, `SessionStart` hook, skills), its content-derived version, the `claude plugin …`
//! command lines that register it, and parsers for what `claude` prints.
//!
//! Layout generated under `LampoPaths::claude_plugin_dir()` (the local marketplace is loaded in
//! place, so the folder stays on disk while the plugin is installed):
//!
//! ```text
//! .claude-plugin/marketplace.json
//! plugins/lampo/.claude-plugin/plugin.json
//! plugins/lampo/.claude-plugin/icon.png    the app icon, when given
//! plugins/lampo/hooks/hooks.json
//! plugins/lampo/skills/<skill-id>/SKILL.md (+ reference files)
//! .installed-version                      written after a successful install
//! ```
//!
//! Registration is always user scope: nothing is ever written inside a project.

use std::collections::BTreeSet;

/// Plugin name; skills are invoked as `lampo:<skill>`.
pub const PLUGIN: &str = "lampo";
/// Name of the local marketplace that lists the plugin.
pub const MARKETPLACE: &str = "lampo";
/// `<plugin>@<marketplace>`, as `claude plugin install` and `claude plugin list` name it.
pub const PLUGIN_ID: &str = "lampo@lampo";
/// File in the plugin folder holding the version installed last.
pub const INSTALLED_MARKER: &str = ".installed-version";
/// `SessionStart` sources the hook runs for (every way a session gets a fresh context).
pub const SESSION_START_MATCHER: &str = "startup|resume|clear|compact";
/// Seconds Claude Code waits for the hook.
pub const HOOK_TIMEOUT_SECS: u32 = 10;
/// Arguments of the `SessionStart` hook (`lampo agent context --hook`).
pub const HOOK_ARGS: [&str; 3] = ["agent", "context", "--hook"];

const AUTHOR: &str = "necos98";
const HOMEPAGE: &str = "https://github.com/necos98/lampo";
const DESCRIPTION: &str = "Lampo local PHP environments: project context at session start and skills to drive the lampo CLI.";

/// A file of a skill, as embedded in the app: `path` is relative to the `skills` folder
/// (`lampo/SKILL.md`, `lampo/reference/db.md`); its first segment is the skill id.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SkillFile {
    pub path: String,
    pub content: String,
}

impl SkillFile {
    pub fn new(path: impl Into<String>, content: impl Into<String>) -> Self {
        Self { path: path.into(), content: content.into() }
    }
}

/// A generated file: `path` is relative to the marketplace root, with forward slashes.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PluginFile {
    pub path: String,
    pub content: String,
}

/// A generated binary file (the plugin icon): `path` as in [`PluginFile`].
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PluginAsset {
    pub path: String,
    pub bytes: Vec<u8>,
}

/// Where the icon goes: `claude plugin validate` looks for `.claude-plugin/icon.png` (a square
/// PNG, 512 to 2048 px).
pub const ICON_PATH: &str = "plugins/lampo/.claude-plugin/icon.png";

/// Everything Lampo writes for Claude Code.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PluginBundle {
    /// `<app version>-h<fnv32 of the generated content>`: Claude Code caches plugins per
    /// version, so the version changes exactly when a file does.
    pub version: String,
    pub files: Vec<PluginFile>,
    /// Binary files (the icon), written as is.
    pub assets: Vec<PluginAsset>,
    /// Folder names under `plugins/lampo/skills` (anything else there is obsolete).
    pub skill_ids: BTreeSet<String>,
}

/// FNV-1a, 32 bit: a stable, dependency-free content hash (not for security).
pub fn fnv32(text: &str) -> u32 {
    fnv32_bytes(text.as_bytes())
}

/// [`fnv32`] of raw bytes.
pub fn fnv32_bytes(bytes: &[u8]) -> u32 {
    bytes.iter().fold(0x811c_9dc5_u32, |hash, byte| (hash ^ u32::from(*byte)).wrapping_mul(0x0100_0193))
}

/// `C:\Users\me\x` -> `C:/Users/me/x` (what the generated JSON and the `claude` arguments use).
pub fn forward_slashes(path: &str) -> String {
    path.replace('\\', "/")
}

/// A relative path that stays inside its root: forward slashes, no drive, no `..`, no empty or
/// `.` segment.
pub fn is_safe_relative(path: &str) -> bool {
    !path.is_empty() && !path.contains('\\') && !path.contains(':') && !path.starts_with('/') && path.split('/').all(|s| !s.is_empty() && s != "." && s != "..")
}

/// UTF-8 text without BOM and with LF line endings, whatever the checkout did.
fn normalize(text: &str) -> String {
    text.trim_start_matches('\u{feff}').replace("\r\n", "\n")
}

fn pretty(value: &serde_json::Value) -> String {
    let mut text = serde_json::to_string_pretty(value).unwrap_or_default();
    text.push('\n');
    text
}

fn marketplace_json() -> String {
    pretty(&serde_json::json!({
        "name": MARKETPLACE,
        "owner": { "name": AUTHOR },
        "metadata": { "description": "Local marketplace generated by the Lampo desktop app for its Claude Code plugin." },
        "plugins": [
            { "name": PLUGIN, "source": format!("./plugins/{PLUGIN}"), "description": DESCRIPTION }
        ],
    }))
}

fn plugin_json(version: &str) -> String {
    pretty(&serde_json::json!({
        "name": PLUGIN,
        "version": version,
        "description": DESCRIPTION,
        "author": { "name": AUTHOR },
        "homepage": HOMEPAGE,
        "repository": HOMEPAGE,
        "license": "MIT",
    }))
}

fn readme() -> String {
    format!(
        "# Lampo for Claude Code\n\n\
         Generated by the Lampo desktop app ({HOMEPAGE}), a local PHP development environment for \
         Windows. At the start of every session a hook runs `lampo agent context --hook`: inside a \
         Lampo project or git worktree it adds the project's URL, PHP version, document root, \
         database connection and services to the context; elsewhere it adds nothing. The skills \
         (`/{PLUGIN}:<skill>`) explain how to drive the `lampo` CLI.\n\n\
         Install, update and remove it from Lampo: Settings > Integrazioni > Claude Code. Do not \
         edit these files: Lampo regenerates them.\n"
    )
}

/// Exec form (`command` + `args`, no shell): no quoting or escaping of the path is needed.
fn hooks_json(exe: &str) -> String {
    pretty(&serde_json::json!({
        "hooks": {
            "SessionStart": [{
                "matcher": SESSION_START_MATCHER,
                "hooks": [{ "type": "command", "command": exe, "args": HOOK_ARGS, "timeout": HOOK_TIMEOUT_SECS }],
            }],
        }
    }))
}

/// The plugin for the CLI at `exe` (the `lampo.exe` copy in the shim dir) with `skills` and,
/// if given, the PNG `icon`. Skill files with an unsafe path are skipped.
pub fn bundle(app_version: &str, exe: &str, skills: &[SkillFile], icon: Option<&[u8]>) -> PluginBundle {
    let exe = forward_slashes(exe);
    let mut skill_files: Vec<PluginFile> = skills
        .iter()
        .map(|s| (forward_slashes(&s.path), normalize(&s.content)))
        .filter(|(path, _)| is_safe_relative(path) && path.contains('/'))
        .map(|(path, content)| PluginFile { path: format!("plugins/{PLUGIN}/skills/{path}"), content })
        .collect();
    skill_files.sort_by(|a, b| a.path.cmp(&b.path));
    let skill_ids = skills.iter().map(|s| forward_slashes(&s.path)).filter(|p| is_safe_relative(p) && p.contains('/')).filter_map(|p| p.split('/').next().map(str::to_string)).collect();

    let mut files = vec![
        PluginFile { path: ".claude-plugin/marketplace.json".into(), content: marketplace_json() },
        PluginFile { path: format!("plugins/{PLUGIN}/README.md"), content: readme() },
        PluginFile { path: format!("plugins/{PLUGIN}/hooks/hooks.json"), content: hooks_json(&exe) },
    ];
    files.extend(skill_files);
    // Everything but the manifest (which carries the version) plus the manifest's other fields.
    let assets: Vec<PluginAsset> = icon.map(|bytes| PluginAsset { path: ICON_PATH.into(), bytes: bytes.to_vec() }).into_iter().collect();
    let mut hashed = format!("{}\n", plugin_json("")).into_bytes();
    let entries = files.iter().map(|f| (&f.path, f.content.as_bytes())).chain(assets.iter().map(|a| (&a.path, a.bytes.as_slice())));
    for (path, content) in entries {
        hashed.extend_from_slice(path.as_bytes());
        hashed.push(b'\n');
        hashed.extend_from_slice(content);
        hashed.push(b'\n');
    }
    let version = format!("{app_version}-h{:08x}", fnv32_bytes(&hashed));
    files.insert(1, PluginFile { path: format!("plugins/{PLUGIN}/.claude-plugin/plugin.json"), content: plugin_json(&version) });
    PluginBundle { version, files, assets, skill_ids }
}

/// Plugin folder below the marketplace root.
pub fn plugin_subdir() -> String {
    format!("plugins/{PLUGIN}")
}

/// One `claude` invocation of a registration flow.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CliStep {
    /// Stable kebab-case id shown (translated) in the GUI's step log.
    pub id: &'static str,
    pub args: Vec<String>,
    /// A failure is logged and the flow goes on (cleanup of something that may not exist).
    pub lenient: bool,
}

fn step(id: &'static str, args: &[&str], lenient: bool) -> CliStep {
    CliStep { id, args: args.iter().map(|a| a.to_string()).collect(), lenient }
}

/// Deterministic (re)installation from the marketplace at `marketplace_dir` (forward slashes):
/// validate both manifests (a failure there is a Lampo bug), drop any previous registration,
/// then add the marketplace and install the plugin in user scope.
pub fn install_steps(marketplace_dir: &str) -> Vec<CliStep> {
    let market = forward_slashes(marketplace_dir).trim_end_matches('/').to_string();
    let plugin = format!("{market}/{}", plugin_subdir());
    vec![
        step("validate-plugin", &["plugin", "validate", &plugin], false),
        step("validate-marketplace", &["plugin", "validate", &market], false),
        step("remove-previous-plugin", &["plugin", "uninstall", PLUGIN_ID, "--scope", "user"], true),
        step("remove-previous-marketplace", &["plugin", "marketplace", "remove", MARKETPLACE], true),
        step("add-marketplace", &["plugin", "marketplace", "add", &market], false),
        step("install-plugin", &["plugin", "install", PLUGIN_ID, "--scope", "user"], false),
    ]
}

/// Removal: both lenient (either may already be gone).
pub fn uninstall_steps() -> Vec<CliStep> {
    vec![step("remove-plugin", &["plugin", "uninstall", PLUGIN_ID, "--scope", "user"], true), step("remove-marketplace", &["plugin", "marketplace", "remove", MARKETPLACE], true)]
}

/// `claude plugin list --json`.
pub fn list_args() -> Vec<String> {
    ["plugin", "list", "--json"].iter().map(|a| a.to_string()).collect()
}

/// Whether `claude plugin list --json` output lists `id` (exact match on `id`). Accepts an array
/// or an object with `plugins`, and noise before/after the JSON.
pub fn plugin_listed(list_json: &str, id: &str) -> bool {
    let parse = |s: &str| serde_json::from_str::<serde_json::Value>(s).ok();
    let value = parse(list_json.trim()).or_else(|| {
        let start = list_json.find(['[', '{'])?;
        let end = list_json.rfind([']', '}'])?;
        parse(list_json.get(start..=end)?)
    });
    let Some(value) = value else { return false };
    let list = match &value {
        serde_json::Value::Array(a) => Some(a),
        v => v.get("plugins").and_then(|p| p.as_array()),
    };
    list.is_some_and(|a| a.iter().any(|p| p.get("id").and_then(|v| v.as_str()) == Some(id)))
}

/// First non-empty line of `claude --version` (`2.1.3 (Claude Code)`), if any.
pub fn parse_version(output: &str) -> Option<String> {
    output.lines().map(str::trim).find(|l| !l.is_empty()).map(str::to_string)
}

/// What the `SessionStart` hook prints to add `context` to the session.
pub fn session_start_output(context: &str) -> String {
    serde_json::json!({ "hookSpecificOutput": { "hookEventName": "SessionStart", "additionalContext": context } }).to_string()
}

#[cfg(test)]
mod tests {
    use std::collections::HashMap;

    use serde_json::Value;

    use super::*;

    const EXE: &str = r"C:\Users\me\AppData\Local\Lampo\bin\lampo.exe";

    fn skills() -> Vec<SkillFile> {
        vec![SkillFile::new("lampo/SKILL.md", "---\r\nname: lampo\r\ndescription: Core.\r\n---\r\nBody\r\n"), SkillFile::new(r"lampo\reference\db.md", "\u{feff}# DB\n")]
    }

    fn json_files(bundle: &PluginBundle) -> HashMap<String, Value> {
        bundle.files.iter().filter(|f| f.path.ends_with(".json")).map(|f| (f.path.clone(), serde_json::from_str(&f.content).expect("valid JSON"))).collect()
    }

    #[test]
    fn files_are_relative_forward_slash_without_bom_or_cr() {
        let b = bundle("0.3.0", EXE, &skills(), None);
        let paths: Vec<&str> = b.files.iter().map(|f| f.path.as_str()).collect();
        assert_eq!(
            paths,
            [
                ".claude-plugin/marketplace.json",
                "plugins/lampo/.claude-plugin/plugin.json",
                "plugins/lampo/README.md",
                "plugins/lampo/hooks/hooks.json",
                "plugins/lampo/skills/lampo/SKILL.md",
                "plugins/lampo/skills/lampo/reference/db.md",
            ]
        );
        for f in &b.files {
            assert!(is_safe_relative(&f.path), "{}", f.path);
            assert!(!f.content.starts_with('\u{feff}'), "BOM in {}", f.path);
            assert!(!f.content.contains('\r'), "CR in {}", f.path);
        }
        assert_eq!(b.skill_ids.iter().map(String::as_str).collect::<Vec<_>>(), ["lampo"]);
    }

    #[test]
    fn manifests_name_the_plugin_and_its_source() {
        let b = bundle("0.3.0", EXE, &skills(), None);
        let f = json_files(&b);
        let m = &f[".claude-plugin/marketplace.json"];
        assert_eq!(m["name"], "lampo");
        assert_eq!(m["owner"]["name"], "necos98");
        assert_eq!(m["plugins"][0]["name"], "lampo");
        assert_eq!(m["plugins"][0]["source"], "./plugins/lampo");
        let p = &f["plugins/lampo/.claude-plugin/plugin.json"];
        assert_eq!(p["name"], "lampo");
        assert_eq!(p["version"], b.version.as_str());
        assert_eq!(p["author"]["name"], "necos98");
        assert_eq!(p["homepage"], "https://github.com/necos98/lampo");
        assert_eq!(p["repository"], "https://github.com/necos98/lampo");
        assert_eq!(p["license"], "MIT");
    }

    #[test]
    fn session_start_hook_runs_the_cli_in_exec_form() {
        let f = json_files(&bundle("0.3.0", EXE, &skills(), None));
        let group = &f["plugins/lampo/hooks/hooks.json"]["hooks"]["SessionStart"][0];
        assert_eq!(group["matcher"], "startup|resume|clear|compact");
        let hook = &group["hooks"][0];
        assert_eq!(hook["type"], "command");
        assert_eq!(hook["command"], "C:/Users/me/AppData/Local/Lampo/bin/lampo.exe");
        assert_eq!(hook["args"], serde_json::json!(["agent", "context", "--hook"]));
        assert_eq!(hook["timeout"], 10);
    }

    #[test]
    fn version_tracks_app_version_exe_and_content() {
        let v = bundle("0.3.0", EXE, &skills(), None).version;
        let (release, hash) = v.split_once("-h").unwrap();
        assert_eq!(release, "0.3.0");
        assert!(hash.len() == 8 && hash.chars().all(|c| c.is_ascii_hexdigit()));
        assert_eq!(v, bundle("0.3.0", EXE, &skills(), None).version, "deterministic");
        // CRLF/BOM of the checkout do not matter.
        let lf: Vec<SkillFile> = skills().into_iter().map(|s| SkillFile::new(s.path.replace('\\', "/"), s.content.replace("\r\n", "\n").replace('\u{feff}', ""))).collect();
        assert_eq!(v, bundle("0.3.0", EXE, &lf, None).version);
        assert_ne!(v, bundle("0.3.1", EXE, &skills(), None).version);
        assert_ne!(v, bundle("0.3.0", r"D:\Lampo\bin\lampo.exe", &skills(), None).version);
        let mut changed = skills();
        changed[0].content.push_str("more\n");
        assert_ne!(v, bundle("0.3.0", EXE, &changed, None).version);
        let mut added = skills();
        added.push(SkillFile::new("lampo-db/SKILL.md", "x"));
        assert_ne!(v, bundle("0.3.0", EXE, &added, None).version);
    }

    #[test]
    fn icon_is_an_asset_that_changes_the_version() {
        let plain = bundle("0.3.0", EXE, &skills(), None);
        assert!(plain.assets.is_empty());
        let png = b"\x89PNG\r\n\x1a\nfake";
        let with = bundle("0.3.0", EXE, &skills(), Some(png));
        assert_eq!(with.assets, [PluginAsset { path: "plugins/lampo/.claude-plugin/icon.png".into(), bytes: png.to_vec() }]);
        assert!(is_safe_relative(ICON_PATH));
        assert_ne!(plain.version, with.version);
        assert_ne!(with.version, bundle("0.3.0", EXE, &skills(), Some(b"\x89PNG other")).version);
        assert_eq!(plain.files.len(), with.files.len(), "the icon is not a text file");
    }

    #[test]
    fn unsafe_skill_paths_are_skipped() {
        let bad = [SkillFile::new("../evil/SKILL.md", "x"), SkillFile::new("C:/x/SKILL.md", "x"), SkillFile::new("/abs/SKILL.md", "x"), SkillFile::new("loose.md", "x")];
        let b = bundle("0.3.0", EXE, &bad, None);
        assert!(!b.files.iter().any(|f| f.path.contains("/skills/")));
        assert!(b.skill_ids.is_empty());
    }

    #[test]
    fn install_steps_validate_then_register_in_user_scope() {
        let steps = install_steps(r"C:\Users\John Doe\AppData\Local\Lampo\agent-plugins\claude-code\");
        let ids: Vec<_> = steps.iter().map(|s| (s.id, s.lenient)).collect();
        assert_eq!(
            ids,
            [
                ("validate-plugin", false),
                ("validate-marketplace", false),
                ("remove-previous-plugin", true),
                ("remove-previous-marketplace", true),
                ("add-marketplace", false),
                ("install-plugin", false),
            ]
        );
        let market = "C:/Users/John Doe/AppData/Local/Lampo/agent-plugins/claude-code";
        assert_eq!(steps[0].args, ["plugin", "validate", &format!("{market}/plugins/lampo")]);
        assert_eq!(steps[1].args, ["plugin", "validate", market]);
        assert_eq!(steps[4].args, ["plugin", "marketplace", "add", market]);
        assert_eq!(steps[5].args, ["plugin", "install", "lampo@lampo", "--scope", "user"]);
        assert!(steps.iter().all(|s| !s.args.iter().any(|a| a == "project" || a == "local")));
        assert!(uninstall_steps().iter().all(|s| s.lenient));
    }

    #[test]
    fn plugin_listed_matches_exact_id_in_either_shape() {
        let entry = r#"{"id":"lampo@lampo","version":"0.3.0-h1","scope":"user","enabled":true}"#;
        assert!(plugin_listed(&format!("[{entry}]"), PLUGIN_ID));
        assert!(plugin_listed(&format!(r#"{{"plugins":[{entry}]}}"#), PLUGIN_ID));
        assert!(plugin_listed(&format!("warning: x\n[{entry}]\n"), PLUGIN_ID));
        for no in ["[]", "{}", "not json", "", r#"[{"id":"lampo@other"}]"#, r#"[{"id":"x-lampo@lampo"}]"#, r#"[{"name":"lampo@lampo"}]"#] {
            assert!(!plugin_listed(no, PLUGIN_ID), "{no}");
        }
    }

    #[test]
    fn version_line_and_hook_output() {
        assert_eq!(parse_version("\n2.1.3 (Claude Code)\n").as_deref(), Some("2.1.3 (Claude Code)"));
        assert_eq!(parse_version("  \n"), None);
        let out: Value = serde_json::from_str(&session_start_output("# Lampo\n\"x\"")).unwrap();
        assert_eq!(out["hookSpecificOutput"]["hookEventName"], "SessionStart");
        assert_eq!(out["hookSpecificOutput"]["additionalContext"], "# Lampo\n\"x\"");
    }

    #[test]
    fn fnv32_known_values() {
        assert_eq!(fnv32(""), 0x811c_9dc5);
        assert_eq!(fnv32("a"), 0xe40c_292c);
    }
}
