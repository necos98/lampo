//! CLI shims and the shim index.
//!
//! The shims (`php.exe`, `composer.exe`, `mysql.exe`, `mysqldump.exe`, `redis-cli.exe`) are
//! copies of one small native executable placed in a PATH directory. On every invocation a shim:
//! 1. reads the shim index file (no IPC with the app — works when the GUI is not running);
//! 2. resolves the project through the [`crate::resolution::ResolverChain`]
//!    (`LAMPO_PROJECT`, current directory, git worktree, global default);
//! 3. asks the matching [`ShimTool`] for the real invocation and runs it, forwarding stdio and
//!    the exit code.
//!
//! Tools are trait implementations (open-closed): adding a shim = implementing [`ShimTool`] and
//! listing it in [`tools::all`].

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::sync::Arc;

use serde::{Deserialize, Serialize};

use crate::error::DomainError;
use crate::php::{ComposerChannel, PhpMinor};
use crate::project::ProjectRoot;
use crate::service::{ServiceId, ServiceKind};
use crate::site::SiteId;

/// Client defaults of one service for a target: the site's instance, or the kind's default
/// instance when the site does not use that kind.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ShimService {
    pub service: ServiceId,
    /// Directory containing the service's clients (`mysql.exe`, `mysqldump.exe`, `redis-cli.exe`).
    pub client_dir: PathBuf,
    pub host: String,
    pub port: u16,
    #[serde(default)]
    pub user: Option<String>,
    /// The site's database/schema, informational (exported as `LAMPO_<prefix>_DATABASE`).
    #[serde(default)]
    pub database: Option<String>,
    /// `DB` → `LAMPO_DB_HOST`, `LAMPO_DB_PORT`, … (from the kind's descriptor).
    pub env_prefix: String,
}

/// Everything a shim needs to run a tool for one project (or the global default).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ShimTarget {
    pub php: PhpMinor,
    /// Install dir of the newest installed patch of `php` (put on PATH by `lampo exec`).
    pub php_dir: PathBuf,
    /// The PHP command-line executable (the package's `EntryRole::Cli`).
    pub php_exe: PathBuf,
    /// Project php.ini dir (exported as `PHPRC`); for the default target, Lampo's default ini dir.
    #[serde(default)]
    pub phprc_dir: Option<PathBuf>,
    /// `composer.phar` matching [`ComposerChannel::for_php`], if installed.
    #[serde(default)]
    pub composer_phar: Option<PathBuf>,
    pub composer_channel: ComposerChannel,
    /// Client defaults per service kind (`mysql`, `redis`, …).
    #[serde(default)]
    pub services: BTreeMap<ServiceKind, ShimService>,
}
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ShimEntry {
    /// A project or a worktree environment (whose root is the worktree folder).
    pub site: SiteId,
    pub root: ProjectRoot,
    pub target: ShimTarget,
}

/// Format version of the index file, bumped on incompatible changes.
/// Version 2: services as a map (`services.mysql`, `services.redis`) and the resolved `php_exe`;
/// version-1 files are migrated on read by the adapter (`lampo-infra-store`).
pub const SHIM_INDEX_VERSION: u32 = 2;

/// The shim index, regenerated by the app whenever projects, settings or packages change.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ShimIndex {
    pub version: u32,
    pub default: Option<ShimTarget>,
    pub projects: Vec<ShimEntry>,
}

impl Default for ShimIndex {
    fn default() -> Self {
        Self { version: SHIM_INDEX_VERSION, default: None, projects: Vec::new() }
    }
}

impl ShimIndex {
    pub fn by_site(&self, site: &SiteId) -> Option<&ShimEntry> {
        self.projects.iter().find(|e| &e.site == site)
    }

    /// The deepest registered folder (project or worktree environment) containing `path`.
    pub fn by_path(&self, path: &str) -> Option<&ShimEntry> {
        self.projects.iter().filter(|e| e.root.contains(path)).max_by_key(|e| e.root.depth())
    }
}

/// A concrete process to start on behalf of a shim.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ShimInvocation {
    pub program: PathBuf,
    pub args: Vec<String>,
    /// Variables to set on top of the inherited environment.
    pub env: Vec<(String, String)>,
}

/// One shimmed tool.
pub trait ShimTool: Send + Sync {
    /// Executable name without extension (`php`, `redis-cli`); the shim binary is copied as
    /// `<name>.exe` and dispatches on its own file name.
    fn name(&self) -> &'static str;
    fn invocation(&self, target: &ShimTarget, args: &[String]) -> Result<ShimInvocation, DomainError>;
}

fn phprc_env(target: &ShimTarget) -> Vec<(String, String)> {
    target.phprc_dir.iter().map(|d| ("PHPRC".to_string(), d.display().to_string())).collect()
}

fn unavailable(tool: &str, reason: &str) -> DomainError {
    DomainError::ToolNotAvailable { tool: tool.to_string(), reason: reason.to_string() }
}

/// Built-in shim tools.
pub mod tools {
    use super::*;

    pub struct Php;
    impl ShimTool for Php {
        fn name(&self) -> &'static str {
            "php"
        }
        fn invocation(&self, target: &ShimTarget, args: &[String]) -> Result<ShimInvocation, DomainError> {
            Ok(ShimInvocation { program: target.php_exe.clone(), args: args.to_vec(), env: phprc_env(target) })
        }
    }

    pub struct Composer;
    impl ShimTool for Composer {
        fn name(&self) -> &'static str {
            "composer"
        }
        fn invocation(&self, target: &ShimTarget, args: &[String]) -> Result<ShimInvocation, DomainError> {
            let phar = target.composer_phar.as_ref().ok_or_else(|| unavailable("composer", "Composer is not installed for this PHP version"))?;
            let mut a = vec![phar.display().to_string()];
            a.extend_from_slice(args);
            Ok(ShimInvocation { program: target.php_exe.clone(), args: a, env: phprc_env(target) })
        }
    }

    /// The service a client tool talks to, or why it cannot run.
    fn service<'a>(target: &'a ShimTarget, tool: &str, kind: &ServiceKind) -> Result<&'a ShimService, DomainError> {
        target.services.get(kind).ok_or_else(|| unavailable(tool, &format!("no {kind} instance is configured and installed for this project")))
    }

    /// `mysql` / `mysqldump`: the client of the target's MySQL instance, defaulting host/port/user
    /// to that instance. User arguments come last, so explicit options win.
    pub struct MysqlClient {
        pub binary: &'static str,
    }
    impl ShimTool for MysqlClient {
        fn name(&self) -> &'static str {
            self.binary
        }
        fn invocation(&self, target: &ShimTarget, args: &[String]) -> Result<ShimInvocation, DomainError> {
            let m = service(target, self.binary, &ServiceKind::MYSQL)?;
            let mut a = vec![format!("--host={}", m.host), format!("--port={}", m.port)];
            a.extend(m.user.iter().map(|u| format!("--user={u}")));
            a.extend_from_slice(args);
            Ok(ShimInvocation { program: m.client_dir.join(format!("{}.exe", self.binary)), args: a, env: Vec::new() })
        }
    }

    pub struct RedisCli;
    impl ShimTool for RedisCli {
        fn name(&self) -> &'static str {
            "redis-cli"
        }
        fn invocation(&self, target: &ShimTarget, args: &[String]) -> Result<ShimInvocation, DomainError> {
            let r = service(target, "redis-cli", &ServiceKind::REDIS)?;
            let mut a = vec!["-h".to_string(), r.host.clone(), "-p".to_string(), r.port.to_string()];
            a.extend_from_slice(args);
            Ok(ShimInvocation { program: r.client_dir.join("redis-cli.exe"), args: a, env: Vec::new() })
        }
    }

    pub fn all() -> Vec<Arc<dyn ShimTool>> {
        vec![Arc::new(Php), Arc::new(Composer), Arc::new(MysqlClient { binary: "mysql" }), Arc::new(MysqlClient { binary: "mysqldump" }), Arc::new(RedisCli)]
    }

    /// Picks the tool from the shim's own executable name (`C:\...\bin\PHP.EXE` → `php`).
    pub fn for_executable(exe_path: &str, tools: &[Arc<dyn ShimTool>]) -> Option<Arc<dyn ShimTool>> {
        let file = exe_path.rsplit(['\\', '/']).next()?.to_ascii_lowercase();
        let stem = file.strip_suffix(".exe").unwrap_or(&file);
        tools.iter().find(|t| t.name() == stem).cloned()
    }
}

/// Environment for running arbitrary commands with a project's toolchain (`lampo exec`/`env`).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ToolchainEnv {
    /// Directories to put in front of `PATH`, in order.
    pub path_prepend: Vec<PathBuf>,
    /// Variables to set. Only `PHPRC` and `LAMPO_*` names: Lampo never sets framework variables
    /// such as `DB_HOST`, which would silently override the project's `.env`.
    pub vars: Vec<(String, String)>,
}

impl ShimTarget {
    /// Shim dir first (so nested `php`/`composer` calls resolve the same project thanks to
    /// `LAMPO_PROJECT`), then the real tool dirs. Each service exports
    /// `LAMPO_<prefix>_HOST`/`_PORT` (+ `_USER`, `_DATABASE` when known).
    pub fn toolchain_env(&self, site: Option<&SiteId>, shim_dir: &Path) -> ToolchainEnv {
        let mut path_prepend = vec![shim_dir.to_path_buf(), self.php_dir.clone()];
        let mut vars: Vec<(String, String)> = Vec::new();
        if let Some(p) = site {
            vars.push(("LAMPO_PROJECT".into(), p.to_string()));
        }
        vars.push(("LAMPO_PHP_VERSION".into(), self.php.to_string()));
        if let Some(dir) = &self.phprc_dir {
            vars.push(("PHPRC".into(), dir.display().to_string()));
        }
        for s in self.services.values() {
            path_prepend.push(s.client_dir.clone());
            let var = |name: &str| format!("LAMPO_{}_{name}", s.env_prefix);
            vars.push((var("HOST"), s.host.clone()));
            vars.push((var("PORT"), s.port.to_string()));
            vars.extend(s.user.iter().map(|u| (var("USER"), u.clone())));
            vars.extend(s.database.iter().map(|d| (var("DATABASE"), d.clone())));
        }
        ToolchainEnv { path_prepend, vars }
    }
}

#[cfg(test)]
pub(crate) mod tests {
    use super::*;

    pub(crate) fn target(php: &str) -> ShimTarget {
        let php = PhpMinor::parse(php).unwrap();
        let mysql = ShimService {
            service: "mysql-8.4".parse().unwrap(),
            client_dir: PathBuf::from(r"C:\mysql\bin"),
            host: "127.0.0.1".into(),
            port: 3306,
            user: Some("root".into()),
            database: Some("shop".into()),
            env_prefix: "DB".into(),
        };
        ShimTarget {
            php,
            php_dir: PathBuf::from(format!(r"C:\php\{php}")),
            php_exe: PathBuf::from(format!(r"C:\php\{php}\php.exe")),
            phprc_dir: Some(PathBuf::from(r"C:\ini")),
            composer_phar: Some(PathBuf::from(r"C:\composer\composer.phar")),
            composer_channel: ComposerChannel::for_php(php),
            services: [(ServiceKind::MYSQL, mysql)].into(),
        }
    }

    pub(crate) fn entry(id: &str, root: &str, php: &str) -> ShimEntry {
        ShimEntry { site: id.parse().unwrap(), root: ProjectRoot::new(root).unwrap(), target: target(php) }
    }

    fn args(a: &[&str]) -> Vec<String> {
        a.iter().map(|s| s.to_string()).collect()
    }

    #[test]
    fn index_lookup_uses_longest_prefix() {
        let index = ShimIndex { projects: vec![entry("mono", "C:\\sites\\mono", "8.2"), entry("legacy", "C:\\sites\\mono\\legacy", "5.6")], ..Default::default() };
        assert_eq!(index.by_path("C:\\sites\\mono\\legacy\\src").unwrap().site.to_string(), "legacy");
        assert_eq!(index.by_path("c:/sites/mono/app").unwrap().site.to_string(), "mono");
        assert!(index.by_path("C:\\sites\\monolith").is_none());
        assert!(index.by_site(&"legacy".parse().unwrap()).is_some());
    }

    #[test]
    fn tool_dispatch_by_executable_name() {
        let all = tools::all();
        assert_eq!(tools::for_executable("C:\\Users\\x\\bin\\PHP.EXE", &all).unwrap().name(), "php");
        assert_eq!(tools::for_executable("redis-cli.exe", &all).unwrap().name(), "redis-cli");
        assert!(tools::for_executable("node.exe", &all).is_none());
    }

    #[test]
    fn php_and_composer_invocations() {
        let t = target("8.3");
        let php = tools::Php.invocation(&t, &args(&["-v"])).unwrap();
        assert_eq!(php.program, PathBuf::from("C:\\php\\8.3").join("php.exe"));
        assert_eq!(php.env, vec![("PHPRC".to_string(), "C:\\ini".to_string())]);
        let c = tools::Composer.invocation(&t, &args(&["install"])).unwrap();
        assert_eq!(c.args, args(&["C:\\composer\\composer.phar", "install"]));
        let mut no_composer = t.clone();
        no_composer.composer_phar = None;
        assert!(tools::Composer.invocation(&no_composer, &[]).is_err());
    }

    #[test]
    fn mysql_defaults_come_before_user_args() {
        let t = target("8.3");
        let inv = tools::MysqlClient { binary: "mysqldump" }.invocation(&t, &args(&["--port=3307", "shop"])).unwrap();
        assert_eq!(inv.program, PathBuf::from("C:\\mysql\\bin").join("mysqldump.exe"));
        assert_eq!(inv.args, args(&["--host=127.0.0.1", "--port=3306", "--user=root", "--port=3307", "shop"]));
        assert!(tools::RedisCli.invocation(&t, &[]).is_err());
    }

    #[test]
    fn toolchain_env_never_sets_framework_variables() {
        let t = target("8.3");
        let env = t.toolchain_env(Some(&"shop".parse().unwrap()), Path::new("C:\\lampo\\bin"));
        assert_eq!(env.path_prepend[0], PathBuf::from("C:\\lampo\\bin"));
        assert!(env.vars.iter().all(|(k, _)| k == "PHPRC" || k.starts_with("LAMPO_")));
        assert!(env.vars.contains(&("LAMPO_PROJECT".into(), "shop".into())));
        assert!(env.vars.contains(&("LAMPO_DB_DATABASE".into(), "shop".into())));
    }
}
