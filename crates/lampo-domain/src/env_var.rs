//! Environment variables a project sets for its PHP, on the web (`SetEnv` in its vhost) and on
//! the command line (`lampo env`, `lampo exec`, the `php`/`composer` shims), like the
//! `environment:` of a Docker Compose service.
//!
//! The values often hold secrets (API keys, passwords): they are never written to logs, and
//! their `Debug` form is redacted. Names Lampo itself sets ([`is_reserved`]) are refused, so a
//! project can never override Lampo's own variables.
//!
//! As for [`crate::apache_directives::ApacheDirectives`], a *stored* value is only checked
//! structurally when read (name syntax, single-line value), so a file written before a rule
//! existed still loads; [`ProjectEnvVars::validate`] (reserved names, case-insensitive
//! duplicates, count) is enforced when the project is saved, and the consumers skip a reserved
//! name anyway ([`ProjectEnvVars::effective`]).

use std::collections::{BTreeMap, BTreeSet};
use std::fmt;

use serde::{Deserialize, Serialize};

use crate::error::DomainError;

/// Variables Lampo sets for the site's PHP (web and command line), lower-case. A project may not
/// set them, nor anything starting with [`RESERVED_PREFIX`].
const RESERVED_NAMES: &[&str] = &[
    // PHP's configuration: its php.ini (and extra ini folders) are generated by Lampo.
    "phprc",
    "php_ini_scan_dir",
    // The tool directories Lampo puts first on PATH.
    "path",
    // mod_fcgid process settings and the site's temp folder (`FcgidInitialEnv`).
    "php_fcgi_max_requests",
    "php_fcgi_children",
    "temp",
    "tmp",
];

/// Prefix of the variables Lampo exports (`LAMPO_PROJECT`, `LAMPO_DB_HOST`, …), lower-case.
const RESERVED_PREFIX: &str = "lampo_";

/// Whether `name` is a variable Lampo manages (case-insensitive, as Windows compares them).
pub fn is_reserved(name: &str) -> bool {
    let lower = name.to_ascii_lowercase();
    RESERVED_NAMES.contains(&lower.as_str()) || lower.starts_with(RESERVED_PREFIX)
}

/// A variable name: `[A-Za-z_][A-Za-z0-9_]*`, at most [`EnvVarName::MAX_LEN`] characters.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
#[serde(try_from = "String", into = "String")]
pub struct EnvVarName(String);

impl EnvVarName {
    pub const MAX_LEN: usize = 128;

    /// A valid name that Lampo does not manage.
    pub fn new(name: impl AsRef<str>) -> Result<Self, DomainError> {
        let name = Self::parse(name.as_ref().trim())?;
        if is_reserved(name.as_str()) {
            return Err(DomainError::InvalidEnvVarName { name: name.0, reason: "it is managed by Lampo".into() });
        }
        Ok(name)
    }

    /// A name as it may be stored, reserved ones included (syntax only): to remove a variable
    /// that a file written by hand or before a rule holds.
    pub fn existing(name: impl AsRef<str>) -> Result<Self, DomainError> {
        Self::parse(name.as_ref().trim())
    }

    /// Syntax only, for values read back from Lampo's own files.
    fn parse(name: &str) -> Result<Self, DomainError> {
        let mut chars = name.chars();
        let valid = name.len() <= Self::MAX_LEN && chars.next().is_some_and(|c| c.is_ascii_alphabetic() || c == '_') && chars.all(|c| c.is_ascii_alphanumeric() || c == '_');
        if !valid {
            return Err(DomainError::InvalidEnvVarName {
                name: name.to_string(),
                reason: format!("use letters, digits and `_`, not starting with a digit, at most {} characters", Self::MAX_LEN),
            });
        }
        Ok(Self(name.to_string()))
    }

    pub fn as_str(&self) -> &str {
        &self.0
    }

    fn same_as(&self, other: &str) -> bool {
        self.0.eq_ignore_ascii_case(other)
    }
}

impl fmt::Display for EnvVarName {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}

impl TryFrom<String> for EnvVarName {
    type Error = DomainError;
    fn try_from(s: String) -> Result<Self, Self::Error> {
        Self::parse(&s)
    }
}

impl From<EnvVarName> for String {
    fn from(v: EnvVarName) -> Self {
        v.0
    }
}

/// A variable value: one line, no control character (a tab is allowed) and no `${`, which
/// Apache would expand on the `SetEnv` line (it has no escape for it). At most
/// [`EnvVarValue::MAX_LEN`] bytes, so the escaped line stays below Apache's 8 KiB line limit.
/// Errors name the variable, never the value; `Debug` is redacted.
#[derive(Clone, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize)]
#[serde(into = "String")]
pub struct EnvVarValue(String);

impl EnvVarValue {
    pub const MAX_LEN: usize = 4000;

    pub fn new(name: &EnvVarName, value: impl Into<String>) -> Result<Self, DomainError> {
        Self::check(value.into()).map_err(|reason| DomainError::InvalidEnvVarValue { name: name.to_string(), reason: reason.into() })
    }

    fn check(value: String) -> Result<Self, &'static str> {
        if value.contains(['\n', '\r']) {
            return Err("it must be a single line");
        }
        if value.chars().any(|c| c.is_control() && c != '\t') {
            return Err("it contains a control character");
        }
        if value.contains("${") {
            return Err("it contains `${`, which Apache would expand");
        }
        if value.len() > Self::MAX_LEN {
            return Err("it is too long");
        }
        Ok(Self(value))
    }

    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl fmt::Debug for EnvVarValue {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("EnvVarValue(<redacted>)")
    }
}

impl From<EnvVarValue> for String {
    fn from(v: EnvVarValue) -> Self {
        v.0
    }
}

/// The variables of a project, by name. Windows compares names case-insensitively, so
/// [`Self::set`] and [`Self::remove`] do too: setting `app_env` replaces `APP_ENV`.
#[derive(Debug, Clone, PartialEq, Eq, Default, Serialize, Deserialize)]
#[serde(try_from = "BTreeMap<EnvVarName, String>")]
pub struct ProjectEnvVars(BTreeMap<EnvVarName, EnvVarValue>);

/// Structural checks only (name syntax, value shape), for values read back from Lampo's files.
impl TryFrom<BTreeMap<EnvVarName, String>> for ProjectEnvVars {
    type Error = DomainError;
    fn try_from(raw: BTreeMap<EnvVarName, String>) -> Result<Self, Self::Error> {
        let checked = raw.into_iter().map(|(name, value)| EnvVarValue::new(&name, value).map(|value| (name, value)));
        checked.collect::<Result<_, _>>().map(Self)
    }
}

impl ProjectEnvVars {
    /// At most this many variables per project.
    pub const MAX_COUNT: usize = 256;

    /// Validated variables from raw pairs (a DTO, the command line): every name and value
    /// checked and the policy of [`Self::validate`] enforced (the count before parsing more).
    pub fn from_pairs<I, K, V>(pairs: I) -> Result<Self, DomainError>
    where
        I: IntoIterator<Item = (K, V)>,
        K: AsRef<str>,
        V: Into<String>,
    {
        let mut vars = BTreeMap::new();
        let mut seen = BTreeSet::new();
        for (name, value) in pairs {
            if vars.len() == Self::MAX_COUNT {
                return Err(too_many());
            }
            let name = EnvVarName::new(name)?;
            let value = EnvVarValue::new(&name, value)?;
            if !seen.insert(name.as_str().to_ascii_lowercase()) {
                return Err(DomainError::InvalidEnvVarName { name: name.0, reason: "it is given twice (names are case-insensitive)".into() });
            }
            vars.insert(name, value);
        }
        Ok(Self(vars))
    }

    /// The policy: no name Lampo manages, no two names differing only by case, at most
    /// [`Self::MAX_COUNT`] variables.
    pub fn validate(&self) -> Result<(), DomainError> {
        if self.0.len() > Self::MAX_COUNT {
            return Err(too_many());
        }
        if let Some(name) = self.0.keys().find(|n| is_reserved(n.as_str())) {
            return Err(DomainError::InvalidEnvVarName { name: name.to_string(), reason: "it is managed by Lampo".into() });
        }
        let mut seen = BTreeSet::new();
        if let Some(name) = self.0.keys().find(|n| !seen.insert(n.as_str().to_ascii_lowercase())) {
            return Err(DomainError::InvalidEnvVarName { name: name.to_string(), reason: "another variable has the same name in a different case".into() });
        }
        Ok(())
    }

    /// Sets `name`, replacing a variable with the same name in any case.
    pub fn set(&mut self, name: EnvVarName, value: EnvVarValue) {
        self.remove(name.as_str());
        self.0.insert(name, value);
    }

    /// Removes the variable named `name` in any case; `false` when there was none.
    pub fn remove(&mut self, name: &str) -> bool {
        let before = self.0.len();
        self.0.retain(|n, _| !n.same_as(name));
        self.0.len() != before
    }

    /// The value of `name` (case-insensitive).
    pub fn get(&self, name: &str) -> Option<&EnvVarValue> {
        self.0.iter().find(|(n, _)| n.same_as(name)).map(|(_, v)| v)
    }

    /// Every variable, sorted by name.
    pub fn iter(&self) -> impl Iterator<Item = (&EnvVarName, &EnvVarValue)> {
        self.0.iter()
    }

    /// The variables to export: a reserved name (only in a file written by hand or before the
    /// rule) is skipped, so Lampo's own variables always win.
    pub fn effective(&self) -> impl Iterator<Item = (&str, &str)> {
        self.0.iter().filter(|(n, _)| !is_reserved(n.as_str())).map(|(n, v)| (n.as_str(), v.as_str()))
    }

    pub fn is_empty(&self) -> bool {
        self.0.is_empty()
    }
}

fn too_many() -> DomainError {
    DomainError::InvalidEnvVars(format!("at most {} variables per project", ProjectEnvVars::MAX_COUNT))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn vars(pairs: &[(&str, &str)]) -> Result<ProjectEnvVars, DomainError> {
        ProjectEnvVars::from_pairs(pairs.iter().map(|(k, v)| (*k, v.to_string())))
    }

    fn name(n: &str) -> EnvVarName {
        EnvVarName::new(n).unwrap()
    }

    #[test]
    fn names_follow_the_shell_syntax() {
        for ok in ["APP_ENV", "_x", "a1", "DB_PASSWORD"] {
            assert!(EnvVarName::new(ok).is_ok(), "{ok}");
        }
        for bad in ["", "1A", "APP-ENV", "A B", "A=B", "ÀPP", "x.y", &"A".repeat(EnvVarName::MAX_LEN + 1)] {
            assert!(matches!(EnvVarName::new(bad), Err(DomainError::InvalidEnvVarName { .. })), "{bad}");
        }
        assert_eq!(EnvVarName::new("  APP_ENV ").unwrap().as_str(), "APP_ENV");
    }

    #[test]
    fn names_managed_by_lampo_are_refused_in_any_case() {
        for reserved in ["PATH", "Path", "PHPRC", "php_ini_scan_dir", "TEMP", "tmp", "PHP_FCGI_CHILDREN", "PHP_FCGI_MAX_REQUESTS", "LAMPO_PROJECT", "lampo_db_host", "LAMPO_"] {
            let err = EnvVarName::new(reserved).unwrap_err();
            assert!(err.to_string().contains("managed by Lampo"), "{reserved}: {err}");
        }
        for free in ["APP_PATH", "MY_LAMPO", "TEMPLATE", "PHP_VERSION"] {
            assert!(EnvVarName::new(free).is_ok(), "{free}");
        }
    }

    #[test]
    fn values_are_single_lines_apache_can_quote() {
        let n = name("APP_KEY");
        for ok in ["", "base64:abc==", r#"a "quoted" C:\path\"#, "tab\there", "$HOME", "100%", "àèì"] {
            assert!(EnvVarValue::new(&n, ok).is_ok(), "{ok:?}");
        }
        for (bad, reason) in [("a\nb", "single line"), ("a\rb", "single line"), ("a\0b", "control character"), ("${SRVROOT}", "`${`"), (&"x".repeat(EnvVarValue::MAX_LEN + 1), "too long")] {
            let err = EnvVarValue::new(&n, bad).unwrap_err();
            assert!(err.to_string().contains(reason), "{bad:?}: {err}");
        }
    }

    #[test]
    fn errors_and_debug_never_show_the_value() {
        let n = name("DB_PASSWORD");
        let err = EnvVarValue::new(&n, "s3cr3t\n").unwrap_err().to_string();
        assert!(err.contains("DB_PASSWORD") && !err.contains("s3cr3t"), "{err}");
        let v = vars(&[("DB_PASSWORD", "s3cr3t")]).unwrap();
        assert!(!format!("{v:?}").contains("s3cr3t"));
    }

    #[test]
    fn names_are_case_insensitive_like_on_windows() {
        let err = vars(&[("APP_ENV", "a"), ("app_env", "b")]).unwrap_err();
        assert!(err.to_string().contains("twice"), "{err}");
        let mut v = vars(&[("APP_ENV", "local")]).unwrap();
        v.set(name("app_env"), EnvVarValue::new(&name("app_env"), "prod").unwrap());
        assert_eq!(v.iter().map(|(n, _)| n.as_str()).collect::<Vec<_>>(), ["app_env"]);
        assert_eq!(v.get("APP_ENV").unwrap().as_str(), "prod");
        assert!(v.remove("App_Env"));
        assert!(!v.remove("APP_ENV"));
        assert!(v.is_empty());
    }

    #[test]
    fn the_count_is_bounded() {
        let many: Vec<(String, String)> = (0..=ProjectEnvVars::MAX_COUNT).map(|i| (format!("V{i}"), String::new())).collect();
        assert!(matches!(ProjectEnvVars::from_pairs(many), Err(DomainError::InvalidEnvVars(_))));
    }

    #[test]
    fn stored_variables_load_and_fail_validation_later() {
        let stored: ProjectEnvVars = serde_json::from_str(r#"{"PATH": "C:/evil", "APP_ENV": "local"}"#).unwrap();
        assert!(stored.validate().is_err());
        assert_eq!(stored.effective().collect::<Vec<_>>(), [("APP_ENV", "local")], "a reserved name is never exported");
        let twice: ProjectEnvVars = serde_json::from_str(r#"{"A": "1", "a": "2"}"#).unwrap();
        assert!(twice.validate().unwrap_err().to_string().contains("different case"));
        assert!(serde_json::from_str::<ProjectEnvVars>(r#"{"A-B": "1"}"#).is_err(), "the name syntax is still checked");
        assert!(serde_json::from_str::<ProjectEnvVars>(r#"{"A": "1\n2"}"#).is_err(), "so is a multi-line value");
    }

    #[test]
    fn serialises_as_a_plain_map() {
        let v = vars(&[("B", "2"), ("A", "1")]).unwrap();
        assert_eq!(serde_json::to_string(&v).unwrap(), r#"{"A":"1","B":"2"}"#);
        assert_eq!(serde_json::from_str::<ProjectEnvVars>(r#"{"A":"1","B":"2"}"#).unwrap(), v);
    }
}
