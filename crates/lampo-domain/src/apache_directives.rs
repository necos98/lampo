//! Free-text Apache directives a project appends inside its `<VirtualHost>`, and the policy
//! that keeps them from running programs, loading code or exposing the disk.
//!
//! The text reaches Apache verbatim and comes from the GUI, the CLI, agents and imported
//! `.lampo.toml` files, so it is untrusted. [`ApacheDirectives::new`] enforces the whole policy.
//! A *stored* value (project or preset file) is only checked structurally when read, so a file
//! written before a rule existed still loads; [`ApacheDirectives::validate`] is then enforced
//! when the project is saved and when its vhost is generated. `httpd -t` validates the rest.

use serde::{Deserialize, Serialize};

use crate::error::DomainError;

/// Why a directive is refused, keyed by its lower-case name. Sections keep their `<`.
const FORBIDDEN: &[(&str, &str)] = &[
    ("include", "it loads another configuration file"),
    ("includeoptional", "it loads another configuration file"),
    ("loadmodule", "it loads code into Apache"),
    ("loadfile", "it loads code into Apache"),
    ("define", "it changes the variables of Lampo's own configuration"),
    ("undefine", "it changes the variables of Lampo's own configuration"),
    ("scriptalias", "it runs programs as CGI scripts"),
    ("scriptaliasmatch", "it runs programs as CGI scripts"),
    ("rewritemap", "it can run external programs (`prg:`) and read any file"),
    ("fcgidwrapper", "Lampo manages the PHP program of the site"),
    ("fcgidinitialenv", "Lampo manages the environment of the site's PHP"),
    ("fcgidcmdoptions", "Lampo manages how the site's PHP is started"),
    ("<directory", "it grants access to folders on disk: Lampo manages the document root (use <Location> or .htaccess)"),
    ("<directorymatch", "it grants access to folders on disk: Lampo manages the document root (use <Location> or .htaccess)"),
];

/// Log directives whose target (first argument) must be a plain file inside Apache's folders.
const LOG_DIRECTIVES: &[&str] = &["customlog", "errorlog", "transferlog", "globallog"];

/// Directives mapping a URL to a folder (target = second argument).
const ALIAS_DIRECTIVES: &[&str] = &["alias", "aliasmatch"];

/// Environment variables Lampo sets for the site's PHP; a directive must not override them.
const RESERVED_ENV_VARS: &[&str] = &["path", "phprc"];

/// Free-text Apache directives appended inside the project's `<VirtualHost>`.
#[derive(Debug, Clone, PartialEq, Eq, Hash, Default, Serialize, Deserialize)]
#[serde(try_from = "String", into = "String")]
pub struct ApacheDirectives(String);

impl ApacheDirectives {
    pub const MAX_LEN: usize = 16 * 1024;

    /// Validated directives: structure (length, NUL) and the whole policy ([`Self::validate`]).
    pub fn new(text: impl Into<String>) -> Result<Self, DomainError> {
        let directives = Self::stored(text.into())?;
        directives.validate()?;
        Ok(directives)
    }

    /// Structural checks only, for values read back from Lampo's own files.
    fn stored(text: String) -> Result<Self, DomainError> {
        if text.len() > Self::MAX_LEN {
            return Err(invalid("too long"));
        }
        if text.contains('\0') {
            return Err(invalid("contains a NUL character"));
        }
        Ok(Self(text.replace("\r\n", "\n")))
    }

    /// The policy: no nested `<VirtualHost>` and no directive that runs a program, loads code,
    /// changes Lampo's variables or PHP environment, or maps / grants access to arbitrary
    /// folders. Names are case-insensitive; every physical line and every logical line
    /// (joined at a trailing `\`) is checked, so a continuation cannot hide a directive.
    pub fn validate(&self) -> Result<(), DomainError> {
        if contains_virtualhost_tag(&self.0) {
            return Err(invalid("<VirtualHost> blocks are generated by Lampo and cannot be nested"));
        }
        for (line, statement) in statements(&self.0) {
            check_statement(&statement).map_err(|reason| invalid(format!("line {line}: {reason}")))?;
        }
        Ok(())
    }

    pub fn as_str(&self) -> &str {
        &self.0
    }

    pub fn is_empty(&self) -> bool {
        self.0.trim().is_empty()
    }
}

impl TryFrom<String> for ApacheDirectives {
    type Error = DomainError;
    fn try_from(s: String) -> Result<Self, Self::Error> {
        Self::stored(s)
    }
}

impl From<ApacheDirectives> for String {
    fn from(v: ApacheDirectives) -> Self {
        v.0
    }
}

fn invalid(reason: impl Into<String>) -> DomainError {
    DomainError::InvalidApacheDirectives(reason.into())
}

fn contains_virtualhost_tag(text: &str) -> bool {
    let lower = text.to_ascii_lowercase();
    lower.contains("<virtualhost") || lower.contains("</virtualhost")
}

/// Apache's leading whitespace (`apr_isspace`, which includes the vertical tab).
fn is_space(c: char) -> bool {
    c.is_ascii_whitespace() || c == '\x0b'
}

/// Every physical line and every multi-line logical line, with the 1-based number of the line
/// it starts on. Apache joins a line ending in `\` with the next one, verbatim.
fn statements(text: &str) -> Vec<(usize, String)> {
    let mut out = Vec::new();
    let mut pending: Option<(usize, String)> = None;
    for (index, line) in text.split(['\n', '\r']).enumerate() {
        let number = index + 1;
        out.push((number, line.to_string()));
        let continued = line.trim_end_matches(is_space).strip_suffix('\\');
        pending = match (pending.take(), continued) {
            (None, Some(head)) => Some((number, head.to_string())),
            (None, None) => None,
            (Some((start, joined)), Some(head)) => Some((start, joined + head)),
            (Some((start, joined)), None) => {
                out.push((start, joined + line));
                None
            }
        };
    }
    out.extend(pending);
    out
}

/// `Err(reason)` when one directive breaks the policy.
fn check_statement(statement: &str) -> Result<(), String> {
    let statement = statement.trim_start_matches(is_space);
    if statement.is_empty() || statement.starts_with('#') {
        return Ok(());
    }
    let name_len = statement.find(|c: char| is_space(c) || matches!(c, '>' | '"' | '\'')).unwrap_or(statement.len());
    let (raw_name, rest) = statement.split_at(name_len);
    let name = raw_name.to_ascii_lowercase();
    let args = arguments(rest.trim_end_matches(is_space).trim_end_matches('>'));
    let refuse = |reason: &str| Err(format!("`{raw_name}` is not allowed: {reason}"));

    if let Some((_, reason)) = FORBIDDEN.iter().find(|(n, _)| *n == name) {
        return refuse(reason);
    }
    if LOG_DIRECTIVES.contains(&name.as_str()) {
        let target = args.first().map(String::as_str).unwrap_or_default();
        if target.starts_with('|') {
            return refuse("a piped log runs a program");
        }
        if escapes_server_root(target) {
            return refuse("a log may only be written inside Apache's folder (relative path without `..`)");
        }
    }
    if ALIAS_DIRECTIVES.contains(&name.as_str()) && args.get(1).is_some_and(|target| escapes_server_root(target)) {
        return refuse("it maps URLs to a folder outside the project (absolute or `..` path)");
    }
    if name == "rewriterule" && args.get(1).is_some_and(|substitution| is_disk_path(substitution)) {
        return refuse("it rewrites URLs to a file on disk (drive, UNC or `${…}` path)");
    }
    if reads_files_in_expression(&statement.to_ascii_lowercase()) {
        return refuse("its expression reads files on disk (`file`)");
    }
    if let Some(var) = env_vars_set(&name, &args).find(|v| RESERVED_ENV_VARS.contains(&v.to_ascii_lowercase().as_str())) {
        return refuse(&format!("`{var}` is managed by Lampo"));
    }
    Ok(())
}

/// The environment variables a `SetEnv`/`UnsetEnv`/`SetEnvIf*`/`BrowserMatch*` directive writes
/// (`[!]name[=value]` arguments).
fn env_vars_set<'a>(name: &str, args: &'a [String]) -> impl Iterator<Item = &'a str> {
    let range = match name {
        "setenv" => 0..1,
        "unsetenv" => 0..args.len(),
        "setenvifexpr" | "browsermatch" | "browsermatchnocase" => 1..args.len(),
        "setenvif" | "setenvifnocase" => 2..args.len(),
        _ => 0..0,
    };
    args.get(range).unwrap_or_default().iter().map(|arg| {
        let arg = arg.trim_start_matches('!');
        arg.split_once('=').map_or(arg, |(var, _)| var)
    })
}

/// Whether a path argument could point outside Apache's server root: absolute (drive, root,
/// UNC), variable-expanded (`${…}`, resolved by Apache from the environment) or with `..`.
fn escapes_server_root(path: &str) -> bool {
    is_disk_path(path) || path.starts_with(['/', '\\']) || path.split(['/', '\\']).any(|segment| segment.trim() == "..")
}

/// A Windows drive or UNC path, or one built from `${…}` variables. A root-relative `/x` is not
/// one: as a URL target it is a path of the site.
fn is_disk_path(path: &str) -> bool {
    let bytes = path.as_bytes();
    let drive = bytes.len() >= 2 && bytes[0].is_ascii_alphabetic() && bytes[1] == b':';
    drive || path.starts_with("\\\\") || path.starts_with("//") || path.contains("${")
}

/// Whether an Apache expression (`Header … "expr=…"`, `<If>`, `SetEnvIfExpr`) uses the `file`
/// function, which returns the content of any file on disk: `file('…')` or `%{file:…}`.
fn reads_files_in_expression(statement_lower: &str) -> bool {
    const FUNCTION: &str = "file";
    statement_lower.contains("%{file:")
        || statement_lower.match_indices(FUNCTION).any(|(at, _)| {
            let standalone = !statement_lower[..at].chars().next_back().is_some_and(|c| c.is_ascii_alphanumeric() || c == '_');
            standalone && statement_lower[at + FUNCTION.len()..].trim_start_matches(is_space).starts_with('(')
        })
}

/// Apache-style arguments: whitespace-separated words, `"…"` or `'…'` quoted, `\` escaping
/// inside quotes.
fn arguments(text: &str) -> Vec<String> {
    let mut args = Vec::new();
    let mut chars = text.chars().peekable();
    loop {
        while chars.next_if(|c| is_space(*c)).is_some() {}
        let Some(&first) = chars.peek() else { break };
        let mut word = String::new();
        if first == '"' || first == '\'' {
            chars.next();
            while let Some(c) = chars.next() {
                match c {
                    '\\' => {
                        if let Some(escaped) = chars.next() {
                            word.push(escaped);
                        }
                    }
                    c if c == first => break,
                    c => word.push(c),
                }
            }
        } else {
            while let Some(c) = chars.next_if(|c| !is_space(*c)) {
                word.push(c);
            }
        }
        args.push(word);
    }
    args
}

#[cfg(test)]
mod tests {
    use super::*;

    fn refused(text: &str) -> String {
        match ApacheDirectives::new(text) {
            Err(DomainError::InvalidApacheDirectives(reason)) => reason,
            other => panic!("`{text}` should be refused, got {other:?}"),
        }
    }

    #[test]
    fn legitimate_directives_are_accepted() {
        let ok = "Header set X-Test 1\r\n\
                  RewriteEngine On\n\
                  RewriteRule ^old$ /new [R=301,L]\n\
                  SetEnv APP_ENV local\n\
                  SetEnvIf Request_URI \"^/api\" IS_API=1\n\
                  php_value memory_limit 512M\n\
                  <Location /admin>\n    Require ip 127.0.0.1\n</Location>\n\
                  # Include is only mentioned in a comment\n\
                  Alias /docs docs\n\
                  CustomLog logs/shop-extra.log lampo\n\
                  ErrorDocument 404 /404.php";
        assert!(ApacheDirectives::new(ok).is_ok(), "{:?}", ApacheDirectives::new(ok));
    }

    #[test]
    fn virtual_hosts_cannot_be_nested() {
        assert!(refused("</VirtualHost>\n<VirtualHost *:80>").contains("<VirtualHost>"));
    }

    #[test]
    fn piped_logs_are_refused() {
        for text in [
            r#"CustomLog "|C:/Windows/System32/cmd.exe /c calc" common"#,
            "CustomLog |C:/evil.exe common",
            r#"ErrorLog "|C:/evil.exe""#,
            "TransferLog '|C:/evil.exe'",
            r#"GlobalLog "||C:/evil.exe" common"#,
        ] {
            assert!(refused(text).contains("piped log"), "{text}");
        }
    }

    #[test]
    fn logs_outside_the_server_root_are_refused() {
        for text in [
            r#"CustomLog "C:/Users/me/AppData/Roaming/Microsoft/Windows/Start Menu/Programs/Startup/x.bat" "%{X}i""#,
            "ErrorLog ../../evil.log",
            "ErrorLog \"${APPDATA}/x.bat\"",
            "TransferLog \\\\server\\share\\x.log",
        ] {
            assert!(refused(text).contains("inside Apache's folder"), "{text}");
        }
    }

    #[test]
    fn code_loading_and_configuration_variables_are_refused() {
        for (text, reason) in [
            ("Include C:/evil.conf", "loads another configuration file"),
            ("IncludeOptional conf/*.conf", "loads another configuration file"),
            ("LoadModule cgi_module modules/mod_cgi.so", "loads code"),
            ("LoadFile C:/evil.dll", "loads code"),
            ("Define LAMPO_VHOSTS C:/evil/*.conf", "variables"),
            ("UnDefine SRVROOT", "variables"),
            ("ScriptAlias /cgi-bin/ C:/Windows/System32/", "CGI"),
            ("ScriptAliasMatch ^/x C:/x", "CGI"),
            ("RewriteMap run prg:C:/evil.exe", "external programs"),
            ("FcgidWrapper \"C:/Windows/System32/cmd.exe /c calc\" .php", "PHP program"),
            ("FcgidInitialEnv PHPRC C:/evil", "environment"),
        ] {
            assert!(refused(text).contains(reason), "{text}: {}", refused(text));
        }
    }

    #[test]
    fn folders_cannot_be_exposed() {
        assert!(refused("<Directory \"C:/\">\n    Require all granted\n</Directory>").contains("<Directory"));
        assert!(refused("<DirectoryMatch \".*\">\nRequire all granted\n</DirectoryMatch>").contains("<DirectoryMatch"));
        for text in [r#"Alias /c "C:/""#, "Alias /c /", "AliasMatch ^/c(.*) C:/$1", "Alias /up ../../Users", "Alias /e \"${SystemDrive}/\""] {
            assert!(refused(text).contains("outside the project"), "{text}");
        }
    }

    #[test]
    fn files_on_disk_cannot_be_served_through_rewrites_or_expressions() {
        for text in ["RewriteRule ^/leak$ C:/Users/me/.ssh/id_rsa", "RewriteRule ^/x$ \\\\server\\share\\x", "RewriteRule ^/x$ \"${USERPROFILE}/x\""] {
            assert!(refused(text).contains("file on disk"), "{text}");
        }
        for text in ["Header set X-Leak \"expr=%{file:C:/Users/me/.ssh/id_rsa}\"", "<If \"file('C:/secret') =~ /a/\">", "SetEnvIfExpr \"FILE ('x') == 'y'\" X=1"] {
            assert!(refused(text).contains("reads files"), "{text}");
        }
        for ok in ["RewriteRule ^old$ /new [R=301,L]", "RewriteRule ^ index.php [L]", "Header set X-Profile 1", "Header set X-Size \"expr=%{filesize:/x}\""] {
            assert!(ApacheDirectives::new(ok).is_ok(), "{ok}: {:?}", ApacheDirectives::new(ok));
        }
    }

    #[test]
    fn reserved_environment_variables_are_refused() {
        for text in ["SetEnv PATH C:/evil", "SetEnv PHPRC C:/evil", "SetEnvIf Request_URI . PHPRC=C:/evil", "SetEnvIfNoCase Host . !Path", "SetEnvIfExpr \"true\" path=x"] {
            assert!(refused(text).contains("managed by Lampo"), "{text}");
        }
        assert!(ApacheDirectives::new("SetEnv APP_PATH C:/sites/shop").is_ok());
        assert!(ApacheDirectives::new("SetEnv APP_NAME PATH").is_ok(), "only the variable name counts");
    }

    #[test]
    fn names_are_case_insensitive_and_indentation_does_not_hide_them() {
        for text in [
            "include C:/x.conf",
            "  INCLUDE C:/x.conf",
            "\tInClUdE C:/x.conf",
            "\x0bInclude x",
            "<IfModule mod_headers.c>\n\t\tinclude x\n</IfModule>",
            "<directory C:/>",
            "  customlog \"|x\" common",
        ] {
            refused(text);
        }
    }

    #[test]
    fn line_continuations_cannot_hide_a_directive() {
        let reason = refused("Header set X 1\nIncl\\\nude C:/evil.conf");
        assert!(reason.starts_with("line 2:"), "{reason}");
        refused("CustomLog \\\n  \"|C:/evil.exe\" common");
        refused("Header set X 1\rInclude C:/evil.conf");
    }

    #[test]
    fn the_error_names_the_line_and_the_directive() {
        let reason = refused("Header set X 1\n\n  CustomLog \"|cmd.exe\" common");
        assert_eq!(reason, "line 3: `CustomLog` is not allowed: a piped log runs a program");
        let message = ApacheDirectives::new("Include x").unwrap_err().to_string();
        assert!(message.starts_with("invalid Apache directives: line 1: `Include` is not allowed"), "{message}");
    }

    #[test]
    fn stored_directives_load_and_fail_validation_later() {
        let stored: ApacheDirectives = serde_json::from_str(r#""Include C:/evil.conf""#).unwrap();
        assert!(stored.validate().is_err());
        assert!(serde_json::from_str::<ApacheDirectives>("\"a\\u0000b\"").is_err(), "structure is still checked");
        let long = format!("\"{}\"", "x".repeat(ApacheDirectives::MAX_LEN + 1));
        assert!(serde_json::from_str::<ApacheDirectives>(&long).is_err());
    }

    #[test]
    fn line_endings_are_normalised() {
        assert_eq!(ApacheDirectives::new("Header set A 1\r\nHeader set B 2").unwrap().as_str(), "Header set A 1\nHeader set B 2");
    }
}
