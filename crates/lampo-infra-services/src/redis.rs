//! Redis for Windows: `redis-server.exe <config_dir>\redis.conf`. The generated configuration
//! only uses directives understood by every Windows-native build (Microsoft/tporadowski ports
//! 3.x–5.x and the MSYS2/Cygwin builds of 6.x/7.x), plus the heap directives of the
//! Microsoft-lineage ports when such a build is detected. Readiness is a real `PING`; shutdown
//! is a `SHUTDOWN` command over the socket (no `redis-cli` process).

use std::path::Path;
use std::sync::Arc;
use std::time::Duration;

use async_trait::async_trait;
use lampo_domain::ports::{CommandSpec, EventPublisher, ProcessSupervisor, ServiceRunner};
use lampo_domain::service::{ServiceId, ServiceKind, ServiceLaunch, ServiceStatus};
use lampo_domain::tcp_port::Port;
use lampo_domain::PortResult;
use lampo_infra_fs::ensure_dir;
use tokio::io::{AsyncReadExt, AsyncWriteExt};

use crate::config_path::config_file_path;
use crate::service_host::{ServiceDriver, ServiceHost, find_executable, write_if_changed};

/// Microsoft-lineage ports (MSOpenTech, tporadowski) ship `redis.windows.conf` and emulate
/// `fork()` with a memory-mapped heap file sized by `maxheap` (default: all physical RAM).
fn is_microsoft_port(server_exe: &Path) -> bool {
    server_exe.parent().is_some_and(|dir| dir.join("redis.windows.conf").is_file() || dir.join("redis.windows-service.conf").is_file())
}

async fn redis_command(port: Port, command: &[u8], expect_reply: bool) -> Option<String> {
    let attempt = async {
        let mut s = tokio::net::TcpStream::connect(("127.0.0.1", port.get())).await.ok()?;
        s.write_all(command).await.ok()?;
        if !expect_reply {
            return Some(String::new());
        }
        let mut buf = [0u8; 128];
        let n = s.read(&mut buf).await.ok()?;
        Some(String::from_utf8_lossy(&buf[..n]).into_owned())
    };
    tokio::time::timeout(Duration::from_secs(3), attempt).await.ok().flatten()
}

struct RedisDriver;

#[async_trait]
impl ServiceDriver for RedisDriver {
    fn program(&self) -> &'static str {
        "redis-server"
    }

    fn command(&self, launch: &ServiceLaunch) -> PortResult<CommandSpec> {
        let exe = find_executable(&launch.install_dir, "redis-server.exe")?;
        // MSYS2/Cygwin builds read `C:\…` arguments as relative paths: pass the file name and
        // run in the config folder (inside the file, `C:/…` paths work).
        Ok(CommandSpec { working_dir: Some(launch.config_dir.clone()), program: exe, args: vec!["redis.conf".into()], env: Vec::new(), path_prepend: Vec::new() })
    }

    fn startup_timeout(&self) -> Duration {
        Duration::from_secs(20)
    }

    fn stop_grace(&self) -> Duration {
        Duration::from_secs(15)
    }

    async fn probe(&self, launch: &ServiceLaunch) -> bool {
        // `-NOAUTH`: a password was set by the user at runtime, the server is up anyway.
        redis_command(launch.port, b"PING\r\n", true).await.is_some_and(|r| r.starts_with("+PONG") || r.starts_with("-NOAUTH"))
    }

    async fn request_shutdown(&self, launch: &ServiceLaunch) {
        let _ = redis_command(launch.port, b"SHUTDOWN\r\n", false).await;
    }
}

pub struct RedisRunner {
    host: ServiceHost,
    driver: RedisDriver,
}

impl RedisRunner {
    pub fn new(supervisor: Arc<dyn ProcessSupervisor>, events: Arc<dyn EventPublisher>) -> Self {
        Self { host: ServiceHost::new(supervisor, events), driver: RedisDriver }
    }

    /// Pure `redis.conf` rendering. A development cache: loopback only, no snapshots or AOF
    /// (nothing is ever written to a project folder; `dir` pins any manual `SAVE` to Lampo's
    /// data dir), memory capped with errors rather than silent evictions, log to stdout (captured
    /// into `output.log`).
    pub fn render_redis_conf(&self, launch: &ServiceLaunch, microsoft_port: bool) -> String {
        let dir = launch.data_dir.clone().unwrap_or_else(|| launch.config_dir.join("data"));
        let mut conf = format!(
            "# Generated by Lampo before every start: changes are overwritten.\n\
             bind 127.0.0.1\n\
             protected-mode yes\n\
             port {port}\n\
             dir {dir}\n\
             dbfilename dump.rdb\n\
             save \"\"\n\
             appendonly no\n\
             stop-writes-on-bgsave-error no\n\
             logfile \"\"\n\
             loglevel notice\n\
             databases 16\n\
             maxmemory 256mb\n\
             maxmemory-policy noeviction\n",
            port = launch.port,
            dir = config_file_path(&dir),
        );
        if microsoft_port {
            conf.push_str(&format!("# Windows port: keep the fork-emulation heap file small and out of C:\\ root.\nmaxheap 512mb\nheapdir {}\n", config_file_path(&dir)));
        }
        conf
    }
}

#[async_trait]
impl ServiceRunner for RedisRunner {
    fn kind(&self) -> ServiceKind {
        ServiceKind::REDIS
    }

    async fn prepare(&self, launch: &ServiceLaunch) -> PortResult<()> {
        let exe = find_executable(&launch.install_dir, "redis-server.exe")?;
        ensure_dir(&launch.config_dir)?;
        ensure_dir(&launch.log_dir)?;
        let dir = launch.data_dir.clone().unwrap_or_else(|| launch.config_dir.join("data"));
        ensure_dir(&dir)?;
        let conf = self.render_redis_conf(launch, is_microsoft_port(&exe));
        write_if_changed(&launch.config_dir.join("redis.conf"), &conf)
    }

    async fn start(&self, launch: &ServiceLaunch) -> PortResult<()> {
        self.host.start(&self.driver, launch).await
    }

    async fn stop(&self, service: &ServiceId) -> PortResult<()> {
        self.host.stop(&self.driver, service).await
    }

    fn status(&self, service: &ServiceId) -> ServiceStatus {
        self.host.status(service)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::JobObjectSupervisor;
    use lampo_domain::ports::NullEventPublisher;

    #[test]
    fn redis_conf_is_loopback_without_persistence() {
        let r = RedisRunner::new(Arc::new(JobObjectSupervisor::new()), Arc::new(NullEventPublisher));
        let launch = ServiceLaunch {
            service: ServiceId::new(lampo_domain::service::ServiceKind::REDIS, None),
            install_dir: r"C:\pk\redis".into(),
            port: Port::of(6380),
            ui_port: None,
            config_dir: r"C:\gen\redis".into(),
            data_dir: Some(r"C:\Data Dir\redis\data".into()),
            log_dir: r"C:\logs\redis".into(),
        };
        let conf = r.render_redis_conf(&launch, false);
        assert!(conf.contains("bind 127.0.0.1\n"));
        assert!(conf.contains("port 6380\n"));
        assert!(conf.contains("dir \"C:/Data Dir/redis/data\"\n"));
        assert!(conf.contains("save \"\"\n"));
        assert!(conf.contains("appendonly no\n"));
        assert!(!conf.contains("heapdir"), "unknown directives abort non-Microsoft builds");
        assert!(r.render_redis_conf(&launch, true).contains("heapdir \"C:/Data Dir/redis/data\"\n"));
    }

    #[test]
    fn command_uses_a_relative_config_path_for_msys2_builds() {
        let dir = tempfile::tempdir().unwrap();
        std::fs::write(dir.path().join("redis-server.exe"), b"").unwrap();
        let launch = ServiceLaunch {
            service: ServiceId::new(lampo_domain::service::ServiceKind::REDIS, None),
            install_dir: dir.path().to_path_buf(),
            port: Port::of(6380),
            ui_port: None,
            config_dir: r"C:\gen\redis".into(),
            data_dir: None,
            log_dir: r"C:\logs\redis".into(),
        };
        let spec = RedisDriver.command(&launch).unwrap();
        assert_eq!(spec.args, ["redis.conf"]);
        assert_eq!(spec.working_dir.as_deref(), Some(Path::new(r"C:\gen\redis")));
    }
}
