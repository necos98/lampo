/// Built-in shim tools.
pub mod tools {
    use super::mysql_database::{self, SiteDatabase};
    use super::*;

    pub struct Php;
    impl ShimTool for Php {
        fn name(&self) -> &'static str {
            "php"
        }
        fn invocation(&self, target: &ShimTarget, args: &[String], _folders: &dyn FolderProbe) -> Result<ShimInvocation, DomainError> {
            Ok(ShimInvocation { program: target.php_exe.clone(), args: args.to_vec(), env: php_env(target), notice: None })
        }
    }

    pub struct Composer;
    impl ShimTool for Composer {
        fn name(&self) -> &'static str {
            "composer"
        }
        fn invocation(&self, target: &ShimTarget, args: &[String], _folders: &dyn FolderProbe) -> Result<ShimInvocation, DomainError> {
            let phar = target.composer_phar.as_ref().ok_or_else(|| unavailable("composer", "Composer is not installed for this PHP version"))?;
            let mut a = vec![phar.display().to_string()];
            a.extend_from_slice(args);
            Ok(ShimInvocation { program: target.php_exe.clone(), args: a, env: php_env(target), notice: None })
        }
    }

    /// The service a client tool talks to, or why it cannot run.
    fn service<'a>(target: &'a ShimTarget, tool: &str, kind: &ServiceKind) -> Result<&'a ShimService, DomainError> {
        target.services.get(kind).ok_or_else(|| unavailable(tool, &format!("no {kind} instance is configured and installed for this project")))
    }

    /// Character set both MySQL clients default to. Without it the client autodetects it from the
    /// Windows console code page (`cp850`…) even with piped output, so non-Latin-1 text comes back
    /// as `?`; MySQL 5.7's `mysqldump` would default to 3-byte `utf8`.
    pub const MYSQL_CLIENT_CHARSET: &str = "utf8mb4";

    /// The real client of the target's MySQL instance with the instance's defaults:
    /// `[option-file options the user put first] --host --port --user --default-character-set
    /// [extra] <user args>`. Option-file options (`--no-defaults`, `--defaults-file=`, …) must stay
    /// first for the client; everything else the user passes comes after the defaults, so explicit
    /// options win.
    fn mysql_client(m: &ShimService, binary: &str, args: &[String], extra: Option<String>) -> ShimInvocation {
        let (leading, rest) = args.split_at(mysql_args::leading_only_count(args));
        let mut a = leading.to_vec();
        a.extend([format!("--host={}", m.host), format!("--port={}", m.port)]);
        a.extend(m.user.iter().map(|u| format!("--user={u}")));
        a.push(format!("--default-character-set={MYSQL_CLIENT_CHARSET}"));
        a.extend(extra);
        a.extend_from_slice(rest);
        ShimInvocation { program: m.client_dir.join(format!("{binary}.exe")), args: a, env: Vec::new(), notice: None }
    }

    /// `mysql`: also selects the site's database unless the user chose one (a positional
    /// database, `-D`, `--database`; `--database=` with no name means none). The default target
    /// and sites without a database get none. The database goes with the defaults, before the
    /// user's arguments: a positional database the parser missed still overrides it. A site
    /// database whose folder is missing from the instance's data dir is not selected (the client
    /// would refuse to connect, failing even `CREATE DATABASE`): the shim says so in one line.
    pub struct Mysql;
    impl ShimTool for Mysql {
        fn name(&self) -> &'static str {
            "mysql"
        }
        fn invocation(&self, target: &ShimTarget, args: &[String], folders: &dyn FolderProbe) -> Result<ShimInvocation, DomainError> {
            let m = service(target, "mysql", &ServiceKind::MYSQL)?;
            let parsed = mysql_args::parse(args, mysql_args::MYSQL_SHORT_WITH_VALUE);
            let chosen = !parsed.positional.is_empty() || parsed.has_short('D') || parsed.has_long("database");
            let site = if chosen { SiteDatabase::None } else { SiteDatabase::of(m, folders) };
            let mut inv = mysql_client(m, "mysql", args, site.usable().map(|d| format!("--database={d}")));
            if let SiteDatabase::Missing(name) = site {
                inv.notice = Some(mysql_database::missing_notice(name));
            }
            Ok(inv)
        }
    }

    /// `mysqldump`: dumps the site's database when the command names nothing to dump (no
    /// positional argument, no `--all-databases`/`-A`, no `--databases`/`-B`), by appending it as
    /// the positional argument; existing positional arguments are never reinterpreted. A site
    /// database whose folder is missing is not appended: the client gives its own usage error.
    pub struct Mysqldump;
    impl ShimTool for Mysqldump {
        fn name(&self) -> &'static str {
            "mysqldump"
        }
        fn invocation(&self, target: &ShimTarget, args: &[String], folders: &dyn FolderProbe) -> Result<ShimInvocation, DomainError> {
            let m = service(target, "mysqldump", &ServiceKind::MYSQL)?;
            let parsed = mysql_args::parse(args, mysql_args::MYSQLDUMP_SHORT_WITH_VALUE);
            let names_something = !parsed.positional.is_empty() || parsed.has_short('A') || parsed.has_short('B') || parsed.has_long("all-databases") || parsed.has_long("databases");
            let mut inv = mysql_client(m, "mysqldump", args, None);
            if !names_something {
                inv.args.extend(SiteDatabase::of(m, folders).usable().map(str::to_string));
            }
            Ok(inv)
        }
    }

    pub struct RedisCli;
    impl ShimTool for RedisCli {
        fn name(&self) -> &'static str {
            "redis-cli"
        }
        fn invocation(&self, target: &ShimTarget, args: &[String], _folders: &dyn FolderProbe) -> Result<ShimInvocation, DomainError> {
            let r = service(target, "redis-cli", &ServiceKind::REDIS)?;
            let mut a = vec!["-h".to_string(), r.host.clone(), "-p".to_string(), r.port.to_string()];
            a.extend_from_slice(args);
            Ok(ShimInvocation { program: r.client_dir.join("redis-cli.exe"), args: a, env: Vec::new(), notice: None })
        }
    }

    pub fn all() -> Vec<Arc<dyn ShimTool>> {
        vec![Arc::new(Php), Arc::new(Composer), Arc::new(Mysql), Arc::new(Mysqldump), Arc::new(RedisCli)]
    }

    /// Picks the tool from the shim's own executable name (`C:\...\bin\PHP.EXE` → `php`).
    pub fn for_executable(exe_path: &str, tools: &[Arc<dyn ShimTool>]) -> Option<Arc<dyn ShimTool>> {
        let file = exe_path.rsplit(['\\', '/']).next()?.to_ascii_lowercase();
        let stem = file.strip_suffix(".exe").unwrap_or(&file);
        tools.iter().find(|t| t.name() == stem).cloned()
    }
}

/// Environment for running arbitrary commands with a project's toolchain (`lampo exec`/`env`).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ToolchainEnv {
    /// Directories to put in front of `PATH`, in order.
    pub path_prepend: Vec<PathBuf>,
    /// Variables to set: Lampo's own (`PHPRC` and `LAMPO_*` names; it never sets framework
    /// variables such as `DB_HOST`, which would silently override the project's `.env`), then the
    /// variables the project itself declares (`ShimTarget::env_vars`), which never replace them.
    pub vars: Vec<(String, String)>,
}

impl ShimTarget {
    /// Shim dir first (so nested `php`/`composer` calls resolve the same project thanks to
    /// `LAMPO_PROJECT`, which holds inside `LAMPO_PROJECT_ROOT`), then the real tool dirs. Each
    /// service exports `LAMPO_<prefix>_HOST`/`_PORT` (+ `_USER`, `_DATABASE` when known). The
    /// project's own variables come last.
    pub fn toolchain_env(&self, site: Option<(&SiteId, &ProjectRoot)>, shim_dir: &Path) -> ToolchainEnv {
        let mut path_prepend = vec![shim_dir.to_path_buf(), self.php_dir.clone()];
        let mut vars: Vec<(String, String)> = Vec::new();
        if let Some((id, root)) = site {
            vars.push((env_vars::PROJECT.into(), id.to_string()));
            vars.push((env_vars::PROJECT_ROOT.into(), root.to_string()));
        }
        vars.push(("LAMPO_PHP_VERSION".into(), self.php.to_string()));
        if let Some(dir) = &self.phprc_dir {
            vars.push(("PHPRC".into(), dir.display().to_string()));
        }
        for s in self.services.values() {
            path_prepend.push(s.client_dir.clone());
            let var = |name: &str| format!("LAMPO_{}_{name}", s.env_prefix);
            vars.push((var("HOST"), s.host.clone()));
            vars.push((var("PORT"), s.port.to_string()));
            vars.extend(s.user.iter().map(|u| (var("USER"), u.clone())));
            vars.extend(s.database.iter().map(|d| (var("DATABASE"), d.clone())));
        }
        let project = self.env_vars.effective().filter(|(name, _)| !vars.iter().any(|(set, _)| set.eq_ignore_ascii_case(name)));
        let project: Vec<(String, String)> = project.map(|(name, value)| (name.to_string(), value.to_string())).collect();
        vars.extend(project);
        ToolchainEnv { path_prepend, vars }
    }
}

