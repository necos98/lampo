    /// Every folder asked about exists: the site's database is there.
    fn present() -> FakeFolders {
        FakeFolders::new(FolderState::Present)
    }

    pub(crate) fn target(php: &str) -> ShimTarget {
        let php = PhpMinor::parse(php).unwrap();
        let mysql = ShimService {
            service: "mysql-8.4".parse().unwrap(),
            client_dir: PathBuf::from(r"C:\mysql\bin"),
            host: "127.0.0.1".into(),
            port: Port::of(3306),
            user: Some("root".into()),
            database: Some("shop".into()),
            data_dir: Some(PathBuf::from(r"C:\mysql\data")),
            env_prefix: "DB".into(),
        };
        ShimTarget {
            php,
            php_dir: PathBuf::from(format!(r"C:\php\{php}")),
            php_exe: PathBuf::from(format!(r"C:\php\{php}\php.exe")),
            phprc_dir: Some(PathBuf::from(r"C:\ini")),
            composer_phar: Some(PathBuf::from(r"C:\composer\composer.phar")),
            composer_channel: ComposerChannel::for_php(php),
            services: [(ServiceKind::MYSQL, mysql)].into(),
            env_vars: ProjectEnvVars::default(),
        }
    }

    pub(crate) fn entry(id: &str, root: &str, php: &str) -> ShimEntry {
        ShimEntry { site: id.parse().unwrap(), root: ProjectRoot::new(root).unwrap(), target: target(php) }
    }

    fn args(a: &[&str]) -> Vec<String> {
        a.iter().map(|s| s.to_string()).collect()
    }

    #[test]
    fn index_lookup_uses_longest_prefix() {
        let index = ShimIndex { projects: vec![entry("mono", "C:\\sites\\mono", "8.2"), entry("legacy", "C:\\sites\\mono\\legacy", "5.6")], ..Default::default() };
        assert_eq!(index.by_path("C:\\sites\\mono\\legacy\\src").unwrap().site.to_string(), "legacy");
        assert_eq!(index.by_path("c:/sites/mono/app").unwrap().site.to_string(), "mono");
        assert!(index.by_path("C:\\sites\\monolith").is_none());
        assert!(index.by_site(&"legacy".parse().unwrap()).is_some());
    }

    #[test]
    fn tool_dispatch_by_executable_name() {
        let all = tools::all();
        assert_eq!(tools::for_executable("C:\\Users\\x\\bin\\PHP.EXE", &all).unwrap().name(), "php");
        assert_eq!(tools::for_executable("redis-cli.exe", &all).unwrap().name(), "redis-cli");
        assert!(tools::for_executable("node.exe", &all).is_none());
    }

    #[test]
    fn php_and_composer_invocations() {
        let t = target("8.3");
        let php = tools::Php.invocation(&t, &args(&["-v"]), &present()).unwrap();
        assert_eq!(php.program, PathBuf::from("C:\\php\\8.3").join("php.exe"));
        assert_eq!(php.env, vec![("PHPRC".to_string(), "C:\\ini".to_string())]);
        let c = tools::Composer.invocation(&t, &args(&["install"]), &present()).unwrap();
        assert_eq!(c.args, args(&["C:\\composer\\composer.phar", "install"]));
        let mut no_composer = t.clone();
        no_composer.composer_phar = None;
        assert!(tools::Composer.invocation(&no_composer, &[], &present()).is_err());
    }

    const DEFAULTS: [&str; 4] = ["--host=127.0.0.1", "--port=3306", "--user=root", "--default-character-set=utf8mb4"];

    fn mysql(t: &ShimTarget, user: &[&str]) -> Vec<String> {
        tools::Mysql.invocation(t, &args(user), &present()).unwrap().args
    }

    fn mysqldump(t: &ShimTarget, user: &[&str]) -> Vec<String> {
        tools::Mysqldump.invocation(t, &args(user), &present()).unwrap().args
    }

    /// The defaults, then `extra`, then the user's arguments.
    fn expected(extra: &[&str], user: &[&str]) -> Vec<String> {
        args(&[&DEFAULTS[..], extra, user].concat())
    }

    #[test]
    fn mysql_defaults_come_before_user_args() {
        let t = target("8.3");
        let inv = tools::Mysqldump.invocation(&t, &args(&["--port=3307", "shop"]), &present()).unwrap();
        assert_eq!(inv.program, PathBuf::from(r"C:\mysql\bin").join("mysqldump.exe"));
        assert_eq!(inv.args, expected(&[], &["--port=3307", "shop"]));
        assert_eq!(mysql(&t, &["--default-character-set=latin1"]), expected(&["--database=shop"], &["--default-character-set=latin1"]));
        assert!(tools::RedisCli.invocation(&t, &[], &present()).is_err());
    }

    #[test]
    fn mysql_selects_the_sites_database_by_default() {
        let t = target("8.3");
        assert_eq!(mysql(&t, &[]), expected(&["--database=shop"], &[]));
        assert_eq!(mysql(&t, &["-e", "SHOW TABLES"]), expected(&["--database=shop"], &["-e", "SHOW TABLES"]));
        assert_eq!(mysql(&t, &["-N", "-B", "-e", "SELECT 1"]), expected(&["--database=shop"], &["-N", "-B", "-e", "SELECT 1"]));
        assert_eq!(mysql(&t, &["-NBe", "SELECT 1"]), expected(&["--database=shop"], &["-NBe", "SELECT 1"]));
        assert_eq!(mysql(&t, &["--execute", "SELECT 1"]), expected(&["--database=shop"], &["--execute", "SELECT 1"]));
        assert_eq!(mysql(&t, &["-u", "root", "-h", "localhost", "-P", "3307"]), expected(&["--database=shop"], &["-u", "root", "-h", "localhost", "-P", "3307"]));
        assert_eq!(mysql(&t, &["-psecret", "-e", "SELECT 1"]), expected(&["--database=shop"], &["-psecret", "-e", "SELECT 1"]));
        assert_eq!(mysql(&t, &["--password", "-e", "SELECT 1"]), expected(&["--database=shop"], &["--password", "-e", "SELECT 1"]));
        assert_eq!(mysql(&t, &["--"]), expected(&["--database=shop"], &["--"]));
    }

