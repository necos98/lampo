//! CLI shims and the shim index.
//!
//! The shims (`php.exe`, `composer.exe`, `mysql.exe`, `mysqldump.exe`, `redis-cli.exe`) are
//! copies of one small native executable placed in a PATH directory. On every invocation a shim:
//! 1. reads the shim index file (no IPC with the app — works when the GUI is not running);
//! 2. resolves the project through the [`crate::resolution::ResolverChain`]
//!    (`LAMPO_PROJECT`, current directory, git worktree, global default);
//! 3. asks the matching [`ShimTool`] for the real invocation and runs it, forwarding stdio and
//!    the exit code.
//!
//! Tools are trait implementations (open-closed): adding a shim = implementing [`ShimTool`] and
//! listing it in [`tools::all`].

